  assert.ok(!draft.writes.some(field=>['to','cc','subject'].includes(field)));
  assert.ok(calls.every(call=>call.method==='GET'&&call.body===null));
  await page.screenshot({path:resolve(evidence,'inserted-draft-mock.png'),fullPage:true});
  await pane.getByRole('button',{name:'管理公司範本',exact:true}).click();
  await expect(pane.getByRole('alert')).toContainText('沒有操作權限');
  await page.getByLabel('測試角色').selectOption('editor');
  await pane.getByRole('button',{name:'公司帳號登入'}).click();
  await pane.getByRole('button',{name:'管理公司範本',exact:true}).click();
  await pane.getByRole('button',{name:/維護通知/}).click();
  await expect(pane.getByRole('button',{name:'發布已存草稿'})).toHaveCount(0);
  await pane.getByLabel('範本名稱',{exact:true}).fill('更新後維護通知');
